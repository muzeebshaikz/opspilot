"""Seed topic table for the synthetic Acme Technologies knowledge ecosystem.

This is the most important design artifact in the data layer. Each topic carries
TWO vocabularies:

  doc_terms   -- the words the *document* uses (formal, technical, precise)
  user_terms  -- the words a *user* uses (informal, symptom-first, imprecise)

Keeping these disjoint is what creates the S-class (semantic paraphrase) queries
where BM25 must fail and dense retrieval must win. Likewise `error_codes` creates
the L-class (lexical-anchored) queries where dense must fail and BM25 must win.

Without this separation the retrieval experiment cannot demonstrate anything --
see docs/audit/SPEC-AUDIT.md G7.
"""
from __future__ import annotations

from dataclasses import dataclass, field


@dataclass(frozen=True, slots=True)
class Topic:
    key: str
    category: str
    product: str
    department: str
    title: str
    symptom: str
    cause: str
    doc_terms: tuple[str, ...]
    user_terms: tuple[str, ...]
    error_codes: tuple[str, ...]
    fix_steps: tuple[str, ...]
    paraphrase_query: str          # S-class: minimal lexical overlap with doc
    canonical_query: str           # baseline
    prerequisite_of: str | None = None   # builds M-class multi-hop pairs
    access_level: str = "employee"
    platforms: tuple[str, ...] = ("Windows", "macOS")
    distractor_product: str | None = None
    aliases: tuple[str, ...] = field(default=())


def _t(**kw) -> Topic:
    return Topic(**kw)


